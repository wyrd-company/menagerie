#!/usr/bin/env bash
# Integrated browser run of the web UI against the real workspace service.
#
#   web/test/integrated/run.sh up <scratch>   build, start an owned Docker daemon and the fixture
#   web/test/integrated/run.sh test <scratch> run the integrated Playwright project
#   web/test/integrated/run.sh down <scratch> stop the fixture and remove the owned daemon
#
# The fixture is TestBrowserFixture (backend/cmd/menagerie, tags pocketid and
# browser): the workspace service composed as main composes it, the real
# template service, an isolated SSH Git host and a disposable Pocket ID.
# Workspace devcontainers run on an owned docker:dind container that sees
# <scratch>/root at the same path, so their bind mounts resolve; its API is
# published on loopback only and it is removed by its recorded id. Pocket ID
# runs on the ambient daemon as the Pocket ID gate does, removed by its id.
# Nothing here reads a credential; every key is generated by the fixture.
# <scratch> must be a path the ambient Docker daemon sees at the same path
# (for example under /workspaces or $HOME, not a container-private /tmp).
set -euo pipefail
cmd=$1
scratch=$(realpath -m "$2")
repo=$(git -C "$(dirname "$0")" rev-parse --show-toplevel)
port=${MENAGERIE_BROWSER_PORT:-18630}
control=${MENAGERIE_BROWSER_CONTROL_PORT:-18631}
dport=${MENAGERIE_BROWSER_DOCKER_PORT:-23751}
dind_image=${DIND_IMAGE:-docker:29.9.2-dind}
# Anonymous pulls only: never the operator's Docker credential helpers.
export DOCKER_CONFIG
DOCKER_CONFIG=$(mktemp -d)
printf '{}\n' > "$DOCKER_CONFIG/config.json"
trap 'rm -rf "$DOCKER_CONFIG"' EXIT

case "$cmd" in
  up)
    mkdir -p "$scratch/root" "$scratch/logs"
    [ -z "$(ls -A "$scratch/root")" ] || { echo "$scratch/root must be empty" >&2; exit 2; }
    pnpm --dir "$repo/web" build > "$scratch/logs/web-build.log" 2>&1
    test -f "$repo/web/dist/index.html"
    export CARGO_TARGET_DIR=${CARGO_TARGET_DIR:-$scratch/cargo}
    cargo build --locked --release --manifest-path "$repo/template-service/Cargo.toml" > "$scratch/logs/template-service-build.log" 2>&1
    docker run -d --privileged -e DOCKER_TLS_CERTDIR= --label menagerie-test=browser-dind \
      -v "$scratch/root:$scratch/root" -p "127.0.0.1:$dport:2375" \
      "$dind_image" dockerd --host tcp://0.0.0.0:2375 > "$scratch/dind.id"
    for ((i = 0; i < 60; i++)); do
      DOCKER_HOST=tcp://127.0.0.1:$dport docker version >/dev/null 2>&1 && break
      sleep 1
    done
    DOCKER_HOST=tcp://127.0.0.1:$dport docker version --format 'workspace daemon {{.Server.Version}}' | tee "$scratch/logs/daemon.txt"
    # Bind mounts resolve on the daemon: it must see the root at the same path.
    echo "$RANDOM$RANDOM" > "$scratch/root/.probe"
    DOCKER_HOST=tcp://127.0.0.1:$dport docker run --rm -v "$scratch/root:$scratch/root" busybox:1.37 cat "$scratch/root/.probe" \
      | cmp - "$scratch/root/.probe" || { echo "the workspace daemon does not see $scratch/root at the same path" >&2; exit 1; }
    rm "$scratch/root/.probe"
    rm -f "$scratch/info.json"
    (
      cd "$repo/backend"
      env -u DOCKER_HOST \
        MENAGERIE_TEMPLATE_SERVICE="$CARGO_TARGET_DIR/release/menagerie-template-service" \
        MENAGERIE_BROWSER_ROOT="$scratch/root" \
        MENAGERIE_BROWSER_DOCKER_HOST="tcp://127.0.0.1:$dport" \
        MENAGERIE_BROWSER_INFO="$scratch/info.json" \
        MENAGERIE_BROWSER_PORT="$port" MENAGERIE_BROWSER_CONTROL_PORT="$control" \
        go test -tags 'pocketid browser' -run '^TestBrowserFixture$' -count=1 -timeout 0 -v ./cmd/menagerie/ \
        > "$scratch/logs/fixture.log" 2>&1 &
      echo $! > "$scratch/fixture.pid"
    )
    while [ ! -s "$scratch/info.json" ]; do
      kill -0 "$(cat "$scratch/fixture.pid")" 2>/dev/null || { tail -30 "$scratch/logs/fixture.log"; exit 1; }
      sleep 1
    done
    cat "$scratch/info.json"; echo
    ;;
  test)
    MENAGERIE_BROWSER_INFO="$scratch/info.json" pnpm --dir "$repo/web" exec playwright test -c playwright.integrated.config.ts
    ;;
  down)
    # Only the state this run saved counts: the control URL and root in
    # <scratch>/info.json, never the current environment's ports. A control
    # endpoint is shut down only after it answers with this run's root.
    stopped=
    if [ -s "$scratch/info.json" ]; then
      saved_control=$(node -p 'require(process.argv[1]).control' "$scratch/info.json")
      saved_root=$(node -p 'require(process.argv[1]).root' "$scratch/info.json")
      served_root=$(curl -fsS "$saved_control/identity" 2>/dev/null |
        node -e 'let s = ""; process.stdin.on("data", (d) => (s += d)).on("end", () => { try { process.stdout.write(JSON.parse(s).root ?? ""); } catch {} });' || true)
      if [ -n "$served_root" ] && [ "$served_root" = "$saved_root" ]; then
        curl -fsS -X POST "$saved_control/shutdown" >/dev/null && stopped=1
      else
        echo "$saved_control does not serve this run ($saved_root); it was not shut down" >&2
      fi
    fi
    if [ -s "$scratch/fixture.pid" ]; then
      pid=$(cat "$scratch/fixture.pid")
      if kill -0 "$pid" 2>/dev/null; then
        if [ -z "$stopped" ]; then
          echo "fixture process $pid is still running and was not shut down; stop it, then run down again" >&2
          exit 1
        fi
        while kill -0 "$pid" 2>/dev/null; do sleep 1; done
      fi
      tail -3 "$scratch/logs/fixture.log" 2>/dev/null || true
    fi
    if [ -s "$scratch/dind.id" ]; then docker rm -fv "$(cat "$scratch/dind.id")" >/dev/null; fi
    rm -f "$scratch/dind.id" "$scratch/fixture.pid"
    ;;
  *) echo "usage: $0 up|test|down <scratch>" >&2; exit 2 ;;
esac
